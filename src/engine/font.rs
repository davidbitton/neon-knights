/// Fallback for anything outside printable ASCII: a hollow box.
const MISSING: [u8; 8] = [
    0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111, 0,
];

pub fn glyph(ch: char) -> &'static [u8; 8] {
    let c = ch as u32;
    if (FIRST..FIRST + GLYPHS.len() as u32).contains(&c) {
        &GLYPHS[(c - FIRST) as usize]
    } else {
        &MISSING
    }
}

/// Width in pixels of `s` drawn at `scale`.
pub fn text_width(s: &str, scale: i32) -> i32 {
    s.chars().count() as i32 * CELL_W * scale
}

/// Draw `s` with its top-left at (x, y), each font pixel `scale` x `scale`.
pub fn draw_scaled(f: &mut Frame, x: i32, y: i32, s: &str, color: u8, scale: i32) {
    for (i, ch) in s.chars().enumerate() {
        let gx = x + i as i32 * CELL_W * scale;
        for (row, bits) in glyph(ch).iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (1 << (GLYPH_W - 1 - col)) != 0 {
                    let px = gx + col * scale;
                    let py = y + row as i32 * scale;
                    for dy in 0..scale {
                        for dx in 0..scale {
                            f.set(px + dx, py + dy, color);
                        }
                    }
                }
            }
        }
    }
}

pub fn draw(f: &mut Frame, x: i32, y: i32, s: &str, color: u8) {
    draw_scaled(f, x, y, s, color, 1);
}

/// Draw centered horizontally on `cx`.
pub fn draw_centered(f: &mut Frame, cx: i32, y: i32, s: &str, color: u8, scale: i32) {
    draw_scaled(f, cx - text_width(s, scale) / 2, y, s, color, scale);
}

/// Text with a one-(font-)pixel drop shadow, for legibility over art.
pub fn draw_shadowed(f: &mut Frame, x: i32, y: i32, s: &str, color: u8, shadow: u8, scale: i32) {
    draw_scaled(f, x + scale, y + scale, s, shadow, scale);
    draw_scaled(f, x, y, s, color, scale);
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::engine::palette::{BLACK, WHITE};

    #[test]
    fn every_printable_glyph_is_distinct_and_fits() {
        for c in 33u8..127 {
            let g = glyph(c as char);
            assert!(g.iter().any(|r| *r != 0), "{} is blank", c as char);
            assert!(g.iter().all(|r| *r < 32));
            for d in (c + 1)..127 {
                assert_ne!(
                    g,
                    glyph(d as char),
                    "{} and {} look the same",
                    c as char,
                    d as char
                );
            }
        }
        assert!(glyph(' ').iter().all(|r| *r == 0));
        assert_eq!(glyph('\u{e9}'), &MISSING);
    }

    #[test]
    fn draws_into_the_framebuffer() {
        let mut f = Frame::new();
        draw(&mut f, 10, 10, "I", WHITE);
        // 'I' has a 3-pixel top bar at columns 1..4.
        assert_eq!(f.get(10, 10), BLACK);
        assert_eq!(f.get(11, 10), WHITE);
        assert_eq!(f.get(13, 10), WHITE);
        assert_eq!(f.get(12, 13), WHITE);
        let mut g = Frame::new();
        draw_scaled(&mut g, 0, 0, "I", WHITE, 3);
        assert_eq!(g.get(3, 0), WHITE);
        assert_eq!(g.get(2, 0), BLACK);
        assert_eq!(text_width("Chip", 2), 48);
    }
}
